def table(rows, widths, header=True):
    data = [[Paragraph(str(c), cell_bold if (header and i == 0) else cell) for c in r] for i, r in enumerate(rows)]
    t = Table(data, colWidths=[w * cm for w in widths], repeatRows=1 if header else 0)
    style = [("GRID", (0, 0), (-1, -1), 0.4, LINE), ("VALIGN", (0, 0), (-1, -1), "MIDDLE"), ("TOPPADDING", (0, 0), (-1, -1), 4), ("BOTTOMPADDING", (0, 0), (-1, -1), 4)]
    if header:
        style.append(("BACKGROUND", (0, 0), (-1, 0), SOFT))
    t.setStyle(TableStyle(style))
    return t


def figure(name, text, width=16.2):
    path = FIG / name
    if not path.exists():
        return [P(f"(картинка {name} не найдена)", small)]
    w, h = ImageReader(str(path)).getSize()
    return [KeepTogether([Image(str(path), width=width * cm, height=width * cm * h / w), P(text, caption)])]


# numbers from saved logits (numpy only)
def softmax(x):
    e = np.exp(x - x.max(1, keepdims=True))
    return e / e.sum(1, keepdims=True)


def ece(probs, y, bins=10):
    conf, ok = probs.max(1), probs.argmax(1) == y
    edges = np.linspace(0, 1, bins + 1)
    total = 0.0
    for low, high in zip(edges[:-1], edges[1:]):
        m = (conf > low) & (conf <= high)
        if m.any():
            total += m.mean() * abs(conf[m].mean() - ok[m].mean())
    return total


def stats(tag, dataset, model, condition, seed=0):
    files = sorted(LOGITS.glob(f"{tag}_{dataset}_{model}_{seed}_f*.npz"))
    if len(files) < 5:
        return None
    parts = [np.load(f) for f in files]
    logits = np.concatenate([p[f"test_{condition}"] for p in parts])
    y = np.concatenate([p["y_test"] for p in parts])
    probs = softmax(logits)
    acc = float((probs.argmax(1) == y).mean())
    return acc, float(ece(probs, y)), float(probs.max(1).mean() - acc)


def fmt(s, i):
    return "считается" if s is None else f"{s[i]:.2f}"


def esc10_zero_db_table():
    conds = [("clean", "чистый"), ("white_0", "белый, 0 dB"), ("real_0", "речевой фон, 0 dB"), ("esc_0", "звуки природы, 0 dB")]
    rows = [["Модель, обучение", "Условие", "Точность", "ECE (нечестность)", "Уверенность минус точность"]]
    for model, name in [("cnn", "CNN"), ("resnet", "ResNet-18"), ("wav2vec", "Wav2Vec2")]:
        for tag, how in [("base", "на чистом"), ("aug", "с шумом")]:
            for c, cname in conds:
                s = stats(tag, "esc10", model, c)
                rows.append([f"{name}, {how}", cname, fmt(s, 0), fmt(s, 1), fmt(s, 2)])
    return rows


